void touch_event() {
	if (LCD_Touch_is_Touching()) {
		LCD_Touch_Get_Position(&x, &y);

		/* Set all bytes buf as 0xFF to create white line */
		memset(buf, 0x00, 640);
		SSD1289_set_window(lcd, last_x, 0, 1, 320);
		SSD1289_transmit_to_ram(lcd, buf, 640);
		SSD1289_set_window(lcd, 0, last_y, 240, 1);
		SSD1289_transmit_to_ram(lcd, buf, 480);

		/* Set all bytes buf as 0x00 to create black line */
		memset(buf, 0xFF, 640);
		SSD1289_set_window(lcd, x, 0, 1, 320);
		SSD1289_transmit_to_ram(lcd, buf, 640);
		SSD1289_set_window(lcd, 0, y, 240, 1);
		SSD1289_transmit_to_ram(lcd, buf, 480);

		last_x = x;
		last_y = y;

		while (LCD_Touch_is_Touching())
			;
	}
}

