"""Copy exact crypto sources into a standalone Arduino sketch; never alter originals."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent


def digest_tree(path: Path) -> tuple[str, dict[str, str]]:
    files = {
        p.relative_to(path).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(path.rglob("*")) if p.is_file()
    }
    digest = hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()
    return digest, files


def prepare(dsa_library: Path) -> dict:
    kem = ROOT.parent / "firmware/esp32_pqc_demo/src/mlkem768"
    dsa = dsa_library.resolve()
    if not (dsa / "src/MLDSA44.h").is_file():
        raise ValueError("--dsa-library must contain src/MLDSA44.h and library.properties")
    if not (dsa / "library.properties").is_file():
        raise ValueError("Missing ML-DSA library.properties")
    sketch = ROOT / "firmware/esp32_crypto_benchmark"
    # Only copy within this benchmark's generated src; no deletion of user sources.
    pairs = ((kem, sketch / "src/kem"), (dsa / "src", sketch / "src/dsa"))
    for source, target in pairs:
        if target.exists():
            # Never overwrite changed copies or leave stale files in recursive builds.
            if digest_tree(source) != digest_tree(target):
                raise ValueError(f"Generated sources differ: {target}. Move this generated directory aside before preparing again.")
    for source, target in pairs:
        if not target.exists():
            shutil.copytree(source, target)
    licenses = ROOT / "licenses"
    licenses.mkdir(parents=True, exist_ok=True)
    shutil.copy2(dsa / "LICENSE", licenses / "MLDSA-LICENSE")
    shutil.copy2(kem / "LICENSE", licenses / "MLKEM-LICENSE")
    # Arduino stages only recognized sketch extensions, not zetas.inc. Its
    # build_opt.h response file keeps the source include path intact on Windows.
    include_flags = '-I"' + str(sketch / "src/dsa").replace("\\", "/") + '"\n'
    (sketch / "build_opt.h").write_text(include_flags, encoding="utf-8")
    kd, kfiles = digest_tree(sketch / "src/kem")
    dd, dfiles = digest_tree(sketch / "src/dsa")
    props = dict(line.split("=", 1) for line in (dsa / "library.properties").read_text(encoding="utf-8").splitlines() if "=" in line)
    revision = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip() or "unknown"
    # Firmware + preparation logic also fingerprinted; git HEAD alone misses local edits.
    harness = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in (sketch / "esp32_crypto_benchmark.ino", sketch / "benchmark.cpp", sketch / "build_opt.h", ROOT / "prepare.py", ROOT / "build.py")}
    manifest = {"schema": 1, "git_head": revision, "mlkem_tree_sha256": kd,
                "mldsa_tree_sha256": dd, "mldsa_version": props.get("version", "unknown"),
                "mlkem_files": kfiles, "mldsa_files": dfiles, "harness": harness,
                "licenses": digest_tree(licenses)[1]}
    build_id = hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest()
    manifest["build_id"] = build_id
    (ROOT / "source_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    header = "// Generated by prepare.py; do not edit.\n"
    for name, value in (("BENCH_BUILD_ID", build_id), ("BENCH_KEM_HASH", kd), ("BENCH_DSA_HASH", dd), ("BENCH_DSA_VERSION", props.get("version", "unknown"))):
        header += f"#define {name} {json.dumps(value)}\n"
    (sketch / "benchmark_build.h").write_text(header, encoding="utf-8")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dsa-library", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps({"build_id": prepare(args.dsa_library)["build_id"]}, indent=2))
